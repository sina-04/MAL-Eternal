const messages: Record<Locale, Record<MessageKey, string>> = { en, fa };

export function translate(locale: Locale, key: MessageKey, values: Record<string, string | number> = {}): string {
  return Object.entries(values).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    messages[locale][key],
  );
}

export function localeFromRequest(request: Request): Locale {
  return request.headers.get("x-mal-locale") === "fa" ? "fa" : "en";
}

export function formatNumber(value: number | string, locale: Locale): string {
  const number = typeof value === "number" ? value : Number(value);
  return Number.isFinite(number) ? new Intl.NumberFormat(locale === "fa" ? "fa-IR" : "en-US").format(number) : String(value);
}

export function formatUiDate(date: string, locale: Locale): string {
  return new Intl.DateTimeFormat(locale === "fa" ? "fa-IR-u-ca-gregory" : "en-US", {
    month: "short",
    day: "numeric",
    year: "numeric",
    timeZone: "UTC",
  }).format(new Date(`${date}T00:00:00Z`));
}

